// Unit tests for when.js (dates, times and schedules in plain words). No network, no server.
import { looksLikeBooking, zonedParts, zonedToUtc, validTz, parseClock, parseDay, parseWhen, parseDuration, deriveTitle, parseSchedule, describeSchedule, dueAt, formatWhen, timeLabel, sameLocalDay } from './when.js';

let pass = 0, fail = 0;
const check = (n, c, d = '') => { if (c) { pass++; console.log(`  PASS  ${n}`); } else { fail++; console.log(`  FAIL  ${n}${d ? `\n        ${d}` : ''}`); } };
const TZ = 'America/Los_Angeles';
const NOW = new Date('2026-10-26T00:20:00Z'); // Sunday Oct 25 2026, 5:20 PM in Los Angeles (daylight time)
const at = (s) => new Date(s).toISOString();
const w = (text, now = NOW, tz = TZ) => parseWhen(text, { now, tz });
const local = (d, tz = TZ) => { const p = zonedParts(d, tz); return `${p.y}-${String(p.m).padStart(2, '0')}-${String(p.d).padStart(2, '0')} ${String(p.h).padStart(2, '0')}:${String(p.mi).padStart(2, '0')}`; };

console.log('[time zones]');
check('valid zones accepted', validTz('America/Los_Angeles') && validTz('UTC') && validTz('America/Argentina/Buenos_Aires'));
check('junk zones refused', !validTz('') && !validTz('Mars/Base') && !validTz('../etc/passwd') && !validTz(5) && !validTz('America/Los_Angeles; rm'));
check('wall clock in LA', local(NOW) === '2026-10-25 17:20' && zonedParts(NOW, TZ).dow === 0);
check('wall clock in New York is 3 hours ahead', local(NOW, 'America/New_York') === '2026-10-25 20:20');
check('LA 3 PM in daylight time = 22:00 UTC', at(zonedToUtc({ y: 2026, m: 10, d: 26, h: 15, mi: 0 }, TZ)) === '2026-10-26T22:00:00.000Z');
check('LA 3 PM after clocks go back = 23:00 UTC', at(zonedToUtc({ y: 2026, m: 11, d: 2, h: 15, mi: 0 }, TZ)) === '2026-11-02T23:00:00.000Z');
check('round trip', local(zonedToUtc({ y: 2027, m: 3, d: 14, h: 9, mi: 30 }, TZ)) === '2027-03-14 09:30');
check('formatWhen', formatWhen(new Date('2026-10-26T22:00:00Z'), TZ) === 'Mon Oct 26 at 3:00 PM', formatWhen(new Date('2026-10-26T22:00:00Z'), TZ));
check('timeLabel', timeLabel('08:00') === '8:00 AM' && timeLabel('17:30') === '5:30 PM' && timeLabel('00:05') === '12:05 AM' && timeLabel('12:00') === '12:00 PM');

console.log('[clock times]');
const c = (s) => parseClock(s);
check('3pm', c('at 3pm')?.h === 15 && c('at 3pm').vague === false);
check('3:30 PM', c('meet 3:30 PM')?.h === 15 && c('meet 3:30 PM').mi === 30);
check('12am / 12pm', c('12am')?.h === 0 && c('12 pm')?.h === 12);
check('noon / midnight', c('noon')?.h === 12 && c('midnight')?.h === 0);
check('bare "at 3" means afternoon, flagged as a guess', c('at 3')?.h === 15 && c('at 3').vague === true);
check('bare "at 9" means morning', c('at 9')?.h === 9);
check('bare "at 12" is noon', c('at 12')?.h === 12);
check('bare "at 7:30" is morning', c('at 7:30')?.h === 7 && c('at 7:30').mi === 30);
check('"at 15:00" is 24-hour', c('at 15:00')?.h === 15 && c('at 15:00').vague === false || c('at 15:00')?.h === 15);
check('tonight at 8 is PM', c('tonight at 8')?.h === 20);
check('tomorrow morning at 11 is AM', c('tomorrow morning at 11')?.h === 11);
check('"at 3 people" is not a time', c('a table at 3 people') === null);
check('"in 30 minutes" is not a clock time', c('in 30 minutes') === null);
check('13pm / 25 refused', c('13pm') === null && c('at 25') === null);
check('no time', c('schedule a meeting') === null);

console.log('[days]');
const d = (s) => { const r = parseDay(s, { now: NOW, tz: TZ }); return r && `${r.y}-${String(r.m).padStart(2, '0')}-${String(r.d).padStart(2, '0')}`; };
check('today', d('today') === '2026-10-25');
check('tomorrow', d('tomorrow at 3') === '2026-10-26');
check('day after tomorrow', d('day after tomorrow') === '2026-10-27');
check('friday', d('on friday') === '2026-10-30');
check('next monday', d('next monday') === '2026-10-26');
check('sunday (today is Sunday) flagged', parseDay('sunday', { now: NOW, tz: TZ })?.sameDayWeekday === true);
check('october 30', d('oct 30') === '2026-10-30' && d('October 30th') === '2026-10-30');
check('30th of october', d('the 30th of october') === '2026-10-30');
check('10/30', d('10/30') === '2026-10-30');
check('a date that already passed means next year', d('oct 1') === '2027-10-01');
check('feb 30 is not a date', d('feb 30') === null);
check('no day', d('at 3pm') === null);
check('"may" alone is not a date', d('you may call') === null);

console.log('[a moment]');
let r = w('schedule a meeting with Tom at 3');
check('"at 3" with 5:20 PM now rolls to tomorrow 3 PM and says so', r.hasTime && r.vague && r.rolled && local(r.start) === '2026-10-26 15:00', JSON.stringify(r) + local(r.start));
r = w('lunch tomorrow at 12:30pm');
check('tomorrow 12:30 PM', local(r.start) === '2026-10-26 12:30' && !r.vague && !r.rolled);
r = w('call tomorrow at 9');
check('tomorrow at 9 = 9 AM (guess flagged)', local(r.start) === '2026-10-26 09:00' && r.vague);
r = w('install on friday at 2');
check('friday at 2 = 2 PM', local(r.start) === '2026-10-30 14:00');
r = w('see Dana monday at 9am');
check('monday 9 AM', local(r.start) === '2026-10-26 09:00');
r = w('sunday at 9am');
check('"sunday" on a Sunday evening means next Sunday', local(r.start) === '2026-11-01 09:00' && r.rolled, local(r.start));
check('...and that is after clocks go back (PST = 17:00 UTC)', at(r.start) === '2026-11-01T17:00:00.000Z', at(r.start));
r = w('oct 30 at 4:30pm');
check('oct 30 4:30 PM', local(r.start) === '2026-10-30 16:30');
r = w('10/30 at noon');
check('10/30 noon', local(r.start) === '2026-10-30 12:00');
r = w('in 2 hours');
check('in 2 hours = 7:20 PM', local(r.start) === '2026-10-25 19:20' && r.relative);
r = w('in 45 minutes');
check('in 45 minutes', local(r.start) === '2026-10-25 18:05');
r = w('tomorrow');
check('a day but no time', r && r.hasDay && !r.hasTime && r.start === null);
r = w('today at 9am');
check('a time that already passed today is flagged', r.past === true && local(r.start) === '2026-10-25 09:00');
r = w('at 7pm');
check('later today', local(r.start) === '2026-10-25 19:00' && !r.rolled);
check('nothing time-like', w('schedule a meeting with Tom') === null);
check('a different time zone changes the answer', local(w('tomorrow at 3pm', NOW, 'America/New_York').start, 'America/New_York') === '2026-10-26 15:00' && at(w('tomorrow at 3pm', NOW, 'America/New_York').start) === '2026-10-26T19:00:00.000Z');

console.log('[durations and titles]');
check('for 30 minutes', parseDuration('meeting at 3 for 30 minutes') === 30);
check('an hour', parseDuration('call for an hour') === 60);
check('1.5 hours', parseDuration('block off 1.5 hours') === 90);
check('half an hour', parseDuration('half an hour with Sam') === 30);
check('45 min meeting', parseDuration('45 min meeting at 2') === 45);
check('no duration', parseDuration('meeting with Tom at 3') === null);
check('"at 3 minutes" is not a duration of the meeting', parseDuration('at 3pm') === null);
check('absurd durations refused', parseDuration('for 99 hours') === null && parseDuration('for 1 minute') === null);
const tt = (s) => deriveTitle(s);
check('title: meeting with Tom', tt('schedule a meeting with Tom at 3') === 'Meeting with Tom', tt('schedule a meeting with Tom at 3'));
check('title: dentist', tt('put dentist on my calendar friday at 2') === 'Dentist', tt('put dentist on my calendar friday at 2'));
check('title: install', tt('book an install for the Johnsons tomorrow at 9am for 2 hours') === 'Install for the Johnsons', tt('book an install for the Johnsons tomorrow at 9am for 2 hours'));
check('title: polite', tt('can you please schedule a call with Maria on oct 30 at 4:30pm') === 'Call with Maria', tt('can you please schedule a call with Maria on oct 30 at 4:30pm'));
check('title: nothing left', tt('schedule tomorrow at 3') === 'Event', tt('schedule tomorrow at 3'));
check('title: capped at 80', tt(`schedule ${'x'.repeat(200)} tomorrow at 3`).length <= 80);

console.log('[is it a booking?]');
const yes = ['schedule a meeting with Tom at 3', 'put dentist on my calendar friday at 2', 'add a meeting with Sam tomorrow at 10', 'book an install for the Johnsons tomorrow at 9am', 'can you schedule a call with Maria on oct 30 at 4:30pm?', 'plan lunch with Dana friday at noon', 'schedule a meeting', 'please add Dana to my calendar tomorrow at 2', 'reserve the truck monday at 8am'];
const no = ["what's on my schedule tomorrow", 'add milk to my list tomorrow', 'make a spreadsheet of my meetings', 'schedule my agent for monday', 'show my calendar', 'add 3 and 4', 'add a note: call the vet', 'add a note to call Tom tomorrow at 3', 'make a file called meeting.txt', 'set up an agent that runs every morning', 'when is my next meeting', 'how do I schedule a call', 'draft an email to Tom about the meeting at 3', 'create a spreadsheet for my appointments', 'schedule a reminder for tomorrow'];
for (const s of yes) check(`booking: ${s}`, looksLikeBooking(s) === true);
for (const s of no) check(`not a booking: ${s}`, looksLikeBooking(s) === false);

console.log('[agent schedules]');
const s = (x) => parseSchedule(x, { now: NOW, tz: TZ });
const j = (o) => JSON.stringify(o);
check('every weekday at 8am', j(s('every weekday at 8am')) === j({ kind: 'daily', time: '08:00', days: [1, 2, 3, 4, 5] }), j(s('every weekday at 8am')));
check('weekdays at 7:30', j(s('weekdays at 7:30')) === j({ kind: 'daily', time: '07:30', days: [1, 2, 3, 4, 5] }));
check('daily at 5:30 pm', j(s('daily at 5:30 pm')) === j({ kind: 'daily', time: '17:30', days: [0, 1, 2, 3, 4, 5, 6] }));
check('every morning = 8 AM', s('every morning')?.time === '08:00' && s('every morning').days.length === 7);
check('every evening = 6 PM', s('every evening')?.time === '18:00');
check('every monday and thursday at 9', j(s('every monday and thursday at 9')) === j({ kind: 'daily', time: '09:00', days: [1, 4] }), j(s('every monday and thursday at 9')));
check('mondays at 7', j(s('mondays at 7')) === j({ kind: 'daily', time: '07:00', days: [1] }));
check('weekends at 10am', j(s('weekends at 10am')) === j({ kind: 'daily', time: '10:00', days: [0, 6] }));
check('every day with no time is not guessed', s('every day') === null);
check('"monday at 9" (no "every") is a one-time run', s('monday at 9am')?.kind === 'once' && local(new Date(s('monday at 9am').at)) === '2026-10-26 09:00');
check('tomorrow at 9am is once', s('tomorrow at 9am')?.kind === 'once');
check('only when I ask', s('only when I ask')?.kind === 'manual' && s('manual')?.kind === 'manual' && s('on demand')?.kind === 'manual');
check('a time already past is not a schedule', s('today at 9am') === null);
check('gibberish', s('purple monkey') === null && s('') === null);
check('describe: weekday', describeSchedule(s('every weekday at 8am'), TZ) === 'every weekday at 8:00 AM');
check('describe: daily', describeSchedule(s('daily at 5:30pm'), TZ) === 'every day at 5:30 PM');
check('describe: some days', describeSchedule(s('every monday and thursday at 9'), TZ) === 'every Mon, Thu at 9:00 AM');
check('describe: once', describeSchedule(s('tomorrow at 9am'), TZ) === 'once, Mon Oct 26 at 9:00 AM', describeSchedule(s('tomorrow at 9am'), TZ));
check('describe: manual', describeSchedule({ kind: 'manual' }, TZ) === 'only when you ask');

console.log('[when is a schedule due]');
const WD = { kind: 'daily', time: '08:00', days: [1, 2, 3, 4, 5] };
const MON_8_10 = new Date('2026-10-26T15:10:00Z'); // Monday 8:10 AM LA
check('due ten minutes after 8', local(dueAt(WD, { now: MON_8_10, tz: TZ, since: new Date('2026-10-23T15:00:00Z') })) === '2026-10-26 08:00');
check('not due before 8', dueAt(WD, { now: new Date('2026-10-26T14:50:00Z'), tz: TZ, since: new Date('2026-10-23T15:00:00Z') }) === null);
check('not due twice', dueAt(WD, { now: MON_8_10, tz: TZ, since: new Date('2026-10-26T15:00:30Z') }) === null);
check('late by more than 3 hours is skipped', dueAt(WD, { now: new Date('2026-10-26T20:00:00Z'), tz: TZ, since: new Date('2026-10-23T15:00:00Z') }) === null);
check('late by 2 hours still runs', dueAt(WD, { now: new Date('2026-10-26T17:00:00Z'), tz: TZ, since: new Date('2026-10-23T15:00:00Z') }) !== null);
check('not on a Sunday', dueAt(WD, { now: new Date('2026-10-25T15:10:00Z'), tz: TZ, since: new Date('2026-10-23T15:00:00Z') }) === null);
check('created after 8 AM does not fire that morning', dueAt(WD, { now: new Date('2026-10-26T16:00:00Z'), tz: TZ, since: new Date('2026-10-26T15:30:00Z') }) === null);
const LATE = { kind: 'daily', time: '23:30', days: [0, 1, 2, 3, 4, 5, 6] };
check('a run just after midnight still catches last night', local(dueAt(LATE, { now: new Date('2026-10-26T07:10:00Z'), tz: TZ, since: new Date('2026-10-25T00:00:00Z') })) === '2026-10-25 23:30');
const ONCE = { kind: 'once', at: '2026-10-26T16:00:00.000Z' };
check('once: due after its time', dueAt(ONCE, { now: new Date('2026-10-26T16:05:00Z'), tz: TZ, since: new Date('2026-10-25T00:00:00Z') })?.toISOString() === ONCE.at);
check('once: not before', dueAt(ONCE, { now: new Date('2026-10-26T15:55:00Z'), tz: TZ, since: new Date(0) }) === null);
check('once: not after it ran', dueAt(ONCE, { now: new Date('2026-10-26T16:05:00Z'), tz: TZ, since: new Date('2026-10-26T16:00:30Z') }) === null);
check('manual never fires', dueAt({ kind: 'manual' }, { now: NOW, tz: TZ }) === null);
check('broken schedules never fire', dueAt({ kind: 'daily', time: 'x', days: [1] }, { now: NOW, tz: TZ }) === null && dueAt(null, { now: NOW, tz: TZ }) === null && dueAt({ kind: 'once', at: 'nope' }, { now: NOW, tz: TZ }) === null);
check('the same day, same zone', sameLocalDay(new Date('2026-10-26T06:00:00Z'), new Date('2026-10-26T03:00:00Z'), TZ) === true && sameLocalDay(new Date('2026-10-26T06:00:00Z'), new Date('2026-10-26T08:00:00Z'), TZ) === false);

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
